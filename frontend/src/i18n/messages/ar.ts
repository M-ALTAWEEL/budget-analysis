/** Arabic plural for "days": 1 يوم واحد، 2 يومان، 3-10 أيام، 11+ يومًا. */
function days(count: number): string {
  if (count === 1) return "يوم واحد";
  if (count === 2) return "يومان";
  if (count >= 3 && count <= 10) return `${count} أيام`;
  return `${count} يومًا`;
}

